async function seed() {
  const db = getDb();
  console.log("Clearing existing data...");
  await db.delete(questions);
  await db.delete(chapters);
  await db.delete(resources);
  await db.delete(subjects);

  console.log("Inserting subjects...");
  const slugToId = new Map<string, number>();
  for (const s of SUBJECTS) {
    const [{ id }] = await db.insert(subjects).values(s).returning({ id: subjects.id });
    slugToId.set(s.slug, id);
  }

  console.log("Inserting chapters...");
  for (const c of CHAPTERS) {
    const subjectId = slugToId.get(c.subject)!;
    await db.insert(chapters).values({
      subjectId,
      title: c.title,
      summary: c.summary,
      content: c.content,
      sortOrder: c.sortOrder,
    });
  }

  console.log("Inserting resources...");
  await db.insert(resources).values(RESOURCE_SEED.map(({ grp, ...r }) => ({ grp, ...r })));

  console.log("Inserting questions...");
  for (const q of QUESTIONS) {
    const subjectId = slugToId.get(q.subject)!;
    await db.insert(questions).values({
      subjectId,
      stem: q.stem,
      options: JSON.stringify(q.options),
      answer: q.answer,
      explanation: q.explanation,
    });
  }

  console.log("Seeding done.");
  process.exit(0);
}

seed().catch((e) => {
  console.error(e);
  process.exit(1);
});
